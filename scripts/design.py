"""Write each use case's design note (docs/architecture/<use case>.md) and the Terraform inputs
(infra/live/usecases.auto.tfvars.json) from its contract and the feasibility check in reports/dev.json."""

import json
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from pkvai import settings  # noqa: E402


def note(key: str, c: dict, f: dict, sel: dict, ids: list[str]) -> str:
    trials = "\n".join(
        f"| {t['model']} | {t['quality']:.2%} | €{t['cost_per_case_eur']:.4f} | €{t['people_and_leakage_per_case_eur']:.4f} | {t['p95_latency_s']} s | {t['why']} |"
        for t in sel["trials"]
    )
    q = f["quota"]
    data = "\n".join(f"- {x}" for x in f["data"])
    return f"""# {c["name"]}

_Generated by `scripts/design.py` from `config/usecases/{key}.toml` and `reports/dev.json`. Do not edit by hand._

**Owner:** {c["owner"]}. **Purpose:** {c["purpose"]}.

## Model, chosen on the holdout weeks

| Candidate | Quality | Model cost per case | People and money paid wrongly per case | p95 latency | Verdict |
|---|--:|--:|--:|--:|---|
{trials}

Chosen: **{sel["chosen"]}**: of the candidates that clear the contract's gate, the cheapest model, unless a dearer one saves
money per case all in by a margin a paired bootstrap over the holdout cases calls real at 90%
(quality at least {c["gate"]["min_quality"]:.0%}, model cost at most €{c["gate"]["max_cost_per_case_eur"]}, p95 at most {c["gate"]["max_p95_latency_s"]} s).

## Where it runs

**{f["runtime"].capitalize()}**: {f["why"]}. Hosting at the contract's volume ({c["deploy"]["volume_per_day"]} cases a day):
Lambda €{f["lambda_eur_per_month"]:.2f} a month, two always-on Fargate tasks €{f["fargate_eur_per_month"]:.2f}.
{"Inputs above Lambda's 6 MB synchronous payload arrive through S3 and an SQS message carries the key." if f["input_via_s3"] else "Inputs arrive in the SQS message."}
Concurrency at peak: {f["concurrency"]}.

## Dependencies to settle before building

- Bedrock quota: {q["tokens_per_minute_at_peak"]:,} tokens a minute at peak, {q["quota_share"]:.1%} of the account's default quota.
  {"**Ask for a quota increase before launch.**" if q["ask_for_increase"] else "No increase needed."}
- Model access: {", ".join(f"`{i}`" for i in ids)} enabled in the account; the use case's role may call no other model.

## Data

{data}
"""


def main() -> None:
    r = json.loads((ROOT / "reports" / "dev.json").read_text())
    specs = settings.usecases()
    models = settings.platform()["models"]
    out_dir = ROOT / "docs" / "architecture"
    out_dir.mkdir(parents=True, exist_ok=True)
    tf = {}
    for key, c in specs.items():
        f, sel = r["feasibility"][key], r["selection"][key]
        ids = sorted({models[m]["bedrock_id"] for m in [sel["chosen"], c.get("fallback", sel["chosen"]), "large"] if models[m]["bedrock_id"]})
        (out_dir / f"{key}.md").write_text(note(key, c, f, sel, ids))
        tf[c["name"]] = {
            "runtime": f["runtime"],
            "memory_mb": c["deploy"]["memory_mb"],
            "timeout_s": int(math.ceil(c["deploy"]["processing_s"] * settings.platform()["runtime"]["safety_factor"])),
            "concurrency": f["concurrency"],
            "bedrock_model_ids": ids,
            "retention_days": c["data"]["retention_days"],
            "health_data": c["data"]["health"],
            "min_quality": c["gate"]["min_quality"],
        }
    (ROOT / "infra" / "live" / "usecases.auto.tfvars.json").write_text(json.dumps({"usecases": tf}, indent=2) + "\n")


if __name__ == "__main__":
    main()
